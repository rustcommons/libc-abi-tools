"""Generate reproducible ABI matrices and Markdown; never guess unknown defaults."""
import argparse
import collections
import csv
import html
import io
import json
import pathlib
import subprocess

REPO = pathlib.Path(__file__).resolve().parents[1]
DATA = REPO / "data/glibc-history"
SONAMES = dict(zip(("c", "m", "ld", "resolv", "pthread", "dl", "rt", "util"),
                  ("libc.so.6", "libm.so.6", "ld-linux-x86-64.so.2", "libresolv.so.2",
                   "libpthread.so.0", "libdl.so.2", "librt.so.1", "libutil.so.1")))


def run(binary, command):
    return subprocess.run([str(binary), "glibc", command, "--data", str(REPO / "data/glibc")],
                          check=True, stdout=subprocess.PIPE).stdout.decode("utf-8")


def span(releases):
    """Only consecutive numeric minor releases may be compressed into ranges."""
    groups = []
    for release in releases:
        major, minor = map(int, release.split("."))
        if groups and groups[-1][-1][0] == major and groups[-1][-1][1] + 1 == minor:
            groups[-1].append((major, minor))
        else:
            groups.append([(major, minor)])
    return ", ".join("–".join(".".join(map(str, item)) for item in
                              ([g[0]] if len(g) == 1 else [g[0], g[-1]])) for g in groups)


def escaped(value):
    return html.escape(str(value)).replace("|", "&#124;").replace("`", "&#96;")


def generate(binary):
    matrix = run(binary, "matrix")
    changes = run(binary, "changes")
    reader = csv.DictReader(io.StringIO(matrix), delimiter="\t")
    releases = reader.fieldnames[5:]
    rows = list(reader)
    indexed = {(r["library"], r["symbol"], r["version"]): r for r in rows}
    defaults = list(csv.DictReader((DATA / "elf-evidence.tsv").open(encoding="utf-8"), delimiter="\t"))
    profiles = json.loads((DATA / "PROVENANCE.json").read_text(encoding="utf-8"))["elf_profiles"]
    observations = collections.defaultdict(list)
    seen = set()
    default_names = set()
    for item in defaults:
        key = (item["library"], item["symbol"], item["version"])
        identity = (item["profile"], key)
        if identity in seen:
            raise SystemExit("Duplicate ELF evidence: " + str(identity))
        seen.add(identity)
        if item["profile"] not in profiles or profiles[item["profile"]]["release"] != item["release"]:
            raise SystemExit("Unknown or mismatched ELF profile")
        source = next((f for f in profiles[item["profile"]]["files"] if f["library"] == item["library"]), None)
        if not source or item["target"] != "x86_64-unknown-linux-gnu" or item["soname"] != SONAMES[item["library"]] or any(item[field] != source[field] for field in ("input_sha256", "metadata_sha256")):
            raise SystemExit("ELF evidence disagrees with declared input provenance")
        if key not in indexed or item["release"] not in releases or indexed[key][item["release"]] == "absent":
            raise SystemExit("ELF evidence disagrees with ABI membership: " + str(identity))
        expected = "F" if item["type"] in ("FUNC", "IFUNC") else {"OBJECT": "D:", "TLS": "T:"}[item["type"]] + item["size"]
        if expected != indexed[key][item["release"]] or item["default"] not in ("yes", "no"):
            raise SystemExit("ELF evidence disagrees with ABI kind/size or default flag")
        if item["default"] == "yes":
            default_key = (item["profile"], item["library"], item["symbol"])
            if default_key in default_names:
                raise SystemExit("Multiple default interfaces for one symbol/profile")
            default_names.add(default_key)
        observations[key].append(item)
    for profile, meta in profiles.items():
        expected = {key for key, row in indexed.items() if row[meta["release"]] != "absent"}
        actual = {key for seen_profile, key in seen if seen_profile == profile}
        if actual != expected:
            raise SystemExit("Incomplete ELF evidence for " + profile)

    table = ["# Versioned glibc interfaces", "",
             "Generated by `scripts/build-glibc-reference.py`; edit source evidence, not this table.", "",
             "Scope: x86_64 Linux, eight libraries, the 28 pinned snapshot labels 2.17–2.44.",
             "This is the complete union within that scope, not a claim of complete glibc history.",
             "First observed snapshot is **not** the interface's historical introduction.",
             "`symbol@GLIBC_x.y` identifies an ABI interface; it does not date the original function.",
             "Default/native properties are measured only for the named input profiles; all other defaults are unknown.",
             "A new default does not remove an older compatibility interface unless the availability evidence says so.", "",
             "See [the history and test design](../GLIBC-HISTORY.md), [machine matrix](../../data/glibc-history/symbols.tsv),",
             "[all adjacent differences](../../data/glibc-history/changes.tsv), and [input provenance](../../data/glibc-history/PROVENANCE.json).", ""]
    # Comparable source builds: report observed default promotion and retention separately.
    old_profile, new_profile = "gnu-source-2.17", "gnu-source-2.22"
    previous = {(r["library"], r["symbol"]): r for r in defaults if r["profile"] == old_profile and r["default"] == "yes"}
    current = {(r["library"], r["symbol"]): r for r in defaults if r["profile"] == new_profile and r["default"] == "yes"}
    table += ["## Observed default-version changes", "",
              "This comparison uses GNU source builds 2.17 and 2.22. Other measured profiles appear in the interface tables; unmeasured defaults remain unknown.", "",
              "| Library | Symbol | Previous default | New default | Older interface in 2.22 |",
              "| --- | --- | --- | --- | --- |"]
    for key in sorted(previous.keys() & current.keys()):
        old, new = previous[key], current[key]
        if old["version"] != new["version"]:
            retained = any(r["profile"] == new_profile for r in observations[(key[0], key[1], old["version"])])
            table.append(f"| {key[0]} | {escaped(key[1])} | {key[1]}@{old['version']} | {key[1]}@{new['version']} | {'Retained for compatibility' if retained else 'Absent'} |")
    table += ["", "## Complete interface table for covered snapshots", "",
              "F = function (ABI lists do not distinguish FUNC/IFUNC); D = object bytes; T = TLS bytes.",
              "Ranges represent only consecutive covered minor-release labels. Absence is meaningful only inside the declared scope.", "",
              "| Library / SONAME | Versioned interface | First observed snapshot | Present snapshots | ABI properties by snapshot | Measured default / native type | Source evidence |",
              "| --- | --- | --- | --- | --- | --- | --- |"]
    reference_rows = collections.defaultdict(list)
    for row in rows:
        key = (row["library"], row["symbol"], row["version"])
        present = [r for r in releases if row[r] != "absent"]
        properties = collections.defaultdict(list)
        for release in present:
            properties[row[release]].append(release)
        details = "; ".join(f"{r['profile']}: {'default' if r['default'] == 'yes' else 'compatibility'} / {r['type']} / {r['binding']} / {r['visibility']}" for r in observations[key]) or "Unknown (no ELF evidence)"
        first = row["first_observed_snapshot"]
        filename = "ld.abilist" if row["library"] == "ld" else "lib" + row["library"] + ".abilist"
        tree_path = "sysdeps/unix/sysv/linux/x86_64/64/" + ("nptl/" if int(first.split('.')[1]) <= 19 else "") + filename
        # The ABI list in glibc's own repository at the release tag.
        source = f"[ABI list](https://sourceware.org/git/?p=glibc.git;a=blob;f={tree_path};hb=refs/tags/glibc-{first})"
        if observations[key]:
            source += "; [ELF/profile hashes](../../data/glibc-history/elf-evidence.tsv)"
        cells = [row["library"] + " / " + SONAMES[row["library"]], row["symbol"] + "@" + row["version"], first,
                 span(present), "; ".join(kind + " (" + span(labels) + ")" for kind, labels in properties.items()), details]
        reference_rows[row["library"]].append("| " + " | ".join(map(escaped, cells)) + " | " + source + " |")
    columns = table[-2:]
    table = table[:-2]
    pages = {}
    table += ["", "The full reference is split into tables of at most 500 interfaces so each page remains readable.", "",
              "| Library | Interfaces | Complete reference pages |", "| --- | ---: | --- |"]
    for library, lines in sorted(reference_rows.items()):
        links = []
        for start in range(0, len(lines), 500):
            number = start // 500 + 1
            name = f"GLIBC-SYMBOLS-{library}-{number}.md"
            links.append(f"[{number}]({name})")
            pages[REPO / "docs/reference" / name] = "\n".join([
                f"# {SONAMES[library]} interfaces — page {number}", "",
                "Generated table; scope, evidence profiles, default-version interpretation, and licenses are described in",
                "[the reference index](GLIBC-SYMBOLS.md) and [history design](../GLIBC-HISTORY.md).", "",
                *columns, *lines[start:start + 500], ""])
        table.append(f"| {library} / {SONAMES[library]} | {len(lines)} | {', '.join(links)} |")
    table += ["", "## Example: both fmemopen interfaces", "", *columns,
              *[line for line in reference_rows["c"] if "| fmemopen@" in line], ""]
    change_rows = list(csv.DictReader(io.StringIO(changes), delimiter="\t"))
    summary = ["# Adjacent glibc snapshot differences", "", "Generated public ABI changes for the covered x86_64/eight-library scope.",
               "Library moves appear as removals and additions; version tags are never backdated.",
               "Default, behavior, headers, other libraries, and missing historical releases need separate evidence.", "",
               "| From | To | Added interfaces | Removed interfaces | Kind/size changes |",
               "| --- | --- | ---: | ---: | ---: |"]
    for before, after in zip(releases, releases[1:]):
        counts = collections.Counter(r["change"] for r in change_rows if r["from"] == before and r["to"] == after)
        summary.append(f"| {before} | {after} | {counts['added']} | {counts['removed']} | {counts['changed']} |")
    summary += ["", "[Every changed interface](../../data/glibc-history/changes.tsv) · [Full interface reference](GLIBC-SYMBOLS.md)", ""]
    native = {p: {(r["library"], r["symbol"], r["version"]): r for r in defaults if r["profile"] == p}
              for p in (old_profile, new_profile)}
    native_rows = []
    for key in sorted(native[old_profile].keys() | native[new_profile].keys()):
        old, new = native[old_profile].get(key), native[new_profile].get(key)
        properties = ["membership"] if old is None or new is None else ["default", "type", "binding", "visibility", "section_alignment"]
        if old and new and (old["type"] in ("OBJECT", "TLS") or new["type"] in ("OBJECT", "TLS")):
            properties.append("size")
        for prop in properties:
            before = old[prop] if old and prop != "membership" else "present" if old else "absent"
            after = new[prop] if new and prop != "membership" else "present" if new else "absent"
            if before != after:
                native_rows.append([old_profile, new_profile, key[0], key[1] + "@" + key[2], prop, before, after])
    native_stream = io.StringIO(newline="")
    writer = csv.writer(native_stream, delimiter="\t", lineterminator="\n")
    writer.writerow(["from_profile", "to_profile", "library", "interface", "property", "before", "after"])
    writer.writerows(native_rows)
    native_md = ["# Measured native interface differences", "",
                 "GNU source builds: 2.17 versus 2.22, x86_64, eight libraries. Other measured profiles appear in the interface reference; unmeasured releases remain unknown.",
                 "Default changes, native FUNC/IFUNC type, binding, visibility, object/TLS size, and declared section alignment are measured.",
                 "Alignment is a conservative section-placement observation, not proof of required language-level alignment.",
                 "Function byte size, address, and section/group numbers are recorded in the evidence but are not ABI or behavioral change claims.",
                 "Retained compatibility interfaces are distinct from new defaults. Behavior and semantic aliasing require separate tests.", "",
                 "[Source profiles and hashes](../../data/glibc-history/PROVENANCE.json) · [Original observations](../../data/glibc-history/elf-evidence.tsv)", "",
                 "| Library | Interface | Property | 2.17 source build | 2.22 source build |",
                 "| --- | --- | --- | --- | --- |"]
    native_md += ["| " + " | ".join(map(escaped, row[2:])) + " |" for row in native_rows]
    native_md.append("")
    return {**pages, DATA / "symbols.tsv": matrix, DATA / "changes.tsv": changes,
            DATA / "native-differences.tsv": native_stream.getvalue(),
            REPO / "docs/reference/GLIBC-NATIVE-DIFFS.md": "\n".join(native_md),
            REPO / "docs/reference/GLIBC-SYMBOLS.md": "\n".join(table) + "\n",
            REPO / "docs/reference/GLIBC-DIFFS.md": "\n".join(summary)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--binary", type=pathlib.Path, required=True)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    outputs = generate(args.binary.resolve())
    for path, text in outputs.items():
        if args.check:
            if not path.is_file() or path.read_bytes() != text.encode("utf-8"):
                raise SystemExit("Regenerate stale reference: " + str(path))
        else:
            path.write_text(text, encoding="utf-8", newline="\n")
    print("Verified" if args.check else "Generated", "matrix, differences, and Markdown interface reference")


if __name__ == "__main__":
    main()
